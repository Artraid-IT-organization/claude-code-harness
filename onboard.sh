#!/usr/bin/env bash
# onboard.sh — интервью владельца и заполнение конфигурации харнесса под него.
# Запускать ПОСЛЕ install.sh:  bash onboard.sh
#
# Механику (хуки, скиллы, петлю обучения) не трогает. Заполняет три файла,
# которые определяют, КЕМ ассистент для тебя работает: SOUL.md, USER.md, CLAUDE.md.
set -euo pipefail

WS="$HOME/.claude/workspace"
ANS="$WS/.onboarding-answers.md"
STAMP="$(date +%Y%m%d-%H%M%S)"
BAK="$WS/backups/pre-onboard-$STAMP"

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
warn() { printf '  ! %s\n' "$*"; }

[ -f "$WS/SOUL.md" ] || { echo "Не найден $WS/SOUL.md — сначала запусти install.sh"; exit 1; }
command -v claude >/dev/null || {
  echo "Нет Claude Code — он нужен, чтобы заполнить шаблоны."
  echo "Установи: npm i -g @anthropic-ai/claude-code"; exit 1; }

cat <<'EOF'

  ================================================================
   НАСТРОЙКА ХАРНЕССА ПОД СЕБЯ
  ================================================================

  Восемь вопросов. Отвечай свободным текстом и развёрнуто — чем подробнее,
  тем точнее получится конфигурация. Пустой ответ на необязательный вопрос —
  просто Enter.

  После интервью Claude заполнит три файла:
    ~/.claude/workspace/SOUL.md   — кем он для тебя работает
    ~/.claude/workspace/USER.md   — кто ты и как с тобой работать
    ~/CLAUDE.md                   — точка входа, что читать каждую сессию

  Шаблоны будут сохранены — откатиться можно всегда.

EOF
read -rp "  Готов начать? [Enter — да, Ctrl+C — выйти] " _

ask() {  # ask <переменная> <вопрос> <подсказка>
  local __var="$1" __q="$2" __hint="${3:-}"
  printf '\n\033[1m%s\033[0m\n' "$__q"
  [ -n "$__hint" ] && printf '  \033[2m%s\033[0m\n' "$__hint"
  printf '  > '
  IFS= read -r __val
  printf -v "$__var" '%s' "$__val"
}

say "ИНТЕРВЬЮ"
ask NAME     "1. Как тебя зовут?"
ask ROLE     "2. Кто ты по роли — должность и зона ответственности?" \
             "Например: технический директор; руководитель разработки; фаундер; аналитик"
ask BIZ      "3. Чем занимается твоя компания или проект?" \
             "Пара предложений: что за продукт, какие клиенты, чем зарабатываете"
ask PROJECTS "4. Какие проекты ты сейчас ведёшь?" \
             "Коротко: что это и в какой стадии"
ask STACK    "5. Что стоит на этом сервере и с чем ты работаешь?" \
             "Языки, базы, сервисы, что уже развёрнуто"
ask STYLE    "6. Как ты хочешь, чтобы ассистент с тобой работал?" \
             "Больше автономии или больше согласований; коротко или развёрнуто; что раздражает"
ask BOUND    "7. Чего он делать НЕ должен?" \
             "Красные линии: что не трогать, что всегда спрашивать перед действием"
ask GOAL     "8. Что будет означать, что всё это работает?" \
             "Необязательно, но помогает расставить приоритеты"

mkdir -p "$WS" "$BAK"
cat > "$ANS" <<EOF
# Ответы владельца — интервью onboard.sh, $(date +%Y-%m-%d)

**Имя:** $NAME
**Роль и зона ответственности:** $ROLE
**Бизнес или проект:** $BIZ
**Текущие проекты:** $PROJECTS
**Стек и сервер:** $STACK
**Как работать со мной:** $STYLE
**Красные линии:** $BOUND
**Критерий успеха:** $GOAL
EOF
ok "ответы сохранены в $ANS"

say "БЭКАП ШАБЛОНОВ"
cp "$WS/SOUL.md" "$WS/USER.md" "$WS/PROTOCOLS.md" "$BAK/" 2>/dev/null || true
cp "$HOME/CLAUDE.md" "$BAK/" 2>/dev/null || true
ok "шаблоны сохранены в $BAK"

say "ЗАПОЛНЕНИЕ"
echo "  Claude читает шаблоны и твои ответы, заполняет три файла. Минута-другая."

PROMPT=$(cat <<'EOF'
Ты настраиваешь харнесс Claude Code под нового владельца.

КОНТЕКСТ. Файлы ~/.claude/workspace/SOUL.md, ~/.claude/workspace/USER.md и ~/CLAUDE.md —
шаблоны с плейсхолдерами в угловых скобках вида <роль> и комментариями <!-- ... -->,
объясняющими смысл каждого раздела. Методология в них рабочая и проверенная: её надо
сохранить, а плейсхолдеры — заполнить.

ОТВЕТЫ ВЛАДЕЛЬЦА: ~/.claude/workspace/.onboarding-answers.md — прочитай их первыми.

ЗАДАЧА. Заполни три файла:

1. ~/.claude/workspace/SOUL.md — кем ассистент работает в этом контуре.
   Сохрани: структуру, разделение ролей, принцип малых шагов, блок «чего я НЕ делаю»,
   требование честности вместо угождения, доведение до конца.
   Заполни: роль под зону ответственности владельца, список проектов, границы scope.

2. ~/.claude/workspace/USER.md — кто владелец и как с ним работать.
   Целиком по его ответам: имя, роль, бизнес, проекты, стек, стиль работы, красные линии.
   Структуру документа сохрани.

3. ~/CLAUDE.md — точка входа.
   Сохрани все разделы: порядок чтения при старте, гейт исполнителя, экономику контекста,
   правила исходящих артефактов, правило долгих процессов, дисциплину agent.md, петлю обучения.
   Заполни: раздел «Среда» под его сервер и стек, пути к его проектам.

ПРАВИЛА:
- Язык документов — русский, как в шаблонах.
- Тон и плотность держи как в шаблонах: сжато, по делу, без воды.
- НЕ выдумывай фактов, которых нет в ответах владельца. Не уверен — оставь общую
  формулировку или явную пометку «заполнить».
- Убери из заполненных файлов служебные комментарии <!-- ... -->, объясняющие, как
  заполнять: они нужны были шаблону, готовому документу мешают. Комментарии, несущие
  смысл для работы, оставь.
- PROTOCOLS.md НЕ трогай: там универсальная методология. Исключение — если из ответов
  владельца прямо следует другая роль по умолчанию, поправь только эту строку.
- Файлы перезаписывай на месте, по своим путям.

В конце выведи короткий отчёт: что заполнил в каждом файле и что стоит дописать руками.
EOF
)

claude --print --permission-mode acceptEdits "$PROMPT" || {
  warn "claude завершился с ошибкой — шаблоны целы в $BAK"
  exit 1
}

say "ГОТОВО"
cat <<EOF

  Конфигурация заполнена. Что дальше:

  1. Прочитай глазами и поправь:
       ~/.claude/workspace/SOUL.md
       ~/.claude/workspace/USER.md
       ~/CLAUDE.md
     Это твоя конфигурация — она должна звучать так, как ты хочешь.

  2. Откат, если не нравится: шаблоны лежат в
       $BAK

  3. Загляни в ~/.claude/workspace/PROTOCOLS.md — там дисциплина работы: фильтр перед
     ответом, правила подачи цифр, маршрутизация моделей. Файл читается каждую сессию,
     поэтому именно он определяет поведение ассистента сильнее всего. Подгони под себя.

  4. Запусти claude в домашнем каталоге и проверь, как отрабатывает старт сессии.

EOF
